/**
 * Generates `src/shared/ui/icons.tsx` from the Figma SVGs in `design/assets`: colors become
 * `currentColor`, decorative frames (background/border rects) are dropped, attributes are
 * converted to JSX. Run with `node scripts/generate-icons.mjs`.
 */
import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'

const root = path.resolve(import.meta.dirname, '..')
const ICONS = {
  SearchIcon: 'search-icon',
  CartIcon: 'cart-icon',
  LoginIcon: 'iconly-curved-logout',
  HeartIcon: 'heart-1',
  FacebookIcon: 'frame-108',
  InstagramIcon: 'frame-109',
  TwitterIcon: 'frame-110',
  LinkedinIcon: 'frame-111',
  YoutubeIcon: 'frame-112',
  HomeIcon: 'iconly-bold-home',
  UserIcon: 'user',
  ShopIcon: 'shop',
  StarIcon: 'iconly-bold-star',
  FilterIcon: 'frame-402',
  ArrowRightIcon: 'iconly-curved-arrow-right',
}

/** The filter glyph sits inside a 45px button frame: crop to the glyph. */
const VIEWBOX_OVERRIDES = { FilterIcon: '14.5 14.5 18 18' }

const camel = (attr) => attr.replace(/-([a-z])/g, (_, c) => c.toUpperCase())

function convert(svg) {
  const viewBox = /viewBox="([^"]+)"/.exec(svg)[1]
  let body = svg
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/<defs>[\s\S]*?<\/defs>/g, '')
    .replace(/<g clip-path="[^"]*">/g, '<g>')
    // Frames drawn around icons (rounded rects): the UI draws its own borders.
    .replace(/<rect[^>]*\/>/g, '')
    .replace(/(fill|stroke)="(?!none)[^"]*"/g, '$1="currentColor"')
    .replace(/fill="url\([^)]*\)"/g, '')
    .replace(/\s([a-z]+(?:-[a-z]+)+)=/g, (_, attr) => ` ${camel(attr)}=`)
    .replace(/\n/g, '')
    .trim()
  body = body.replace(/<g>([\s\S]*)<\/g>/, '$1')
  return { viewBox, body }
}

let out = `// Generated by scripts/generate-icons.mjs from the Figma SVGs (design/assets). Do not edit.
import type { SVGProps } from 'react'

type IconProps = SVGProps<SVGSVGElement>

/** Decorative by default (\`aria-hidden\`): the control that contains the icon carries the label. */
function base(props: IconProps, viewBox: string) {
  return { viewBox, fill: 'none', 'aria-hidden': true, focusable: false, width: '1em', height: '1em', ...props } as const
}
`
for (const [name, file] of Object.entries(ICONS)) {
  const svg = await readFile(path.join(root, 'design/assets', `${file}.svg`), 'utf8')
  const converted = convert(svg)
  const viewBox = VIEWBOX_OVERRIDES[name] ?? converted.viewBox
  const body = converted.body
  out += `\nexport function ${name}(props: IconProps) {\n  return (\n    <svg {...base(props, '${viewBox}')}>\n      ${body}\n    </svg>\n  )\n}\n`
}
await writeFile(path.join(root, 'src/shared/ui/icons.tsx'), out)
console.log('icons', Object.keys(ICONS).length)
